#!/usr/bin/env node
// Writes docs/20261113-1401-app-terms.json and docs/20261113-1401-APP-TERMS.md from the app's message files.
//
//   npm run terms                       reads ../hubsell-client at origin/main
//   npm run terms -- --client <folder> --ref <branch or commit>
//
// The website cannot read hubsell-client when Cloudflare builds it, so the
// result is committed. Run this again whenever the app's messages change, then
// `npm run build` to see what the new words flag.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { locales, terms } from './20261113-1401-app-terms.config.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};
const client = resolve(root, arg('--client', '../hubsell-client'));
const ref = arg('--ref', 'origin/main');
const MESSAGES = 'src/i18n/messages';

const git = (...a) => execFileSync('git', ['-C', client, ...a], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

let commit;
try {
  commit = git('rev-parse', '--short', ref).trim();
} catch {
  console.error(`\n  Could not read ${ref} in ${client}.`);
  console.error('  Pass the hubsell-client folder with --client, and run `git fetch` in it first.\n');
  process.exit(1);
}
const commitDate = git('show', '-s', '--format=%cs', ref).trim();

// messages[locale]['nav.contacts'] = 'Kontakte'
const messages = {};
for (const locale of locales) {
  messages[locale] = {};
  const files = git('ls-tree', '--name-only', ref, `${MESSAGES}/${locale}/`)
    .split('\n')
    .filter((f) => f.endsWith('.json'));
  for (const file of files) {
    const name = file.split('/').pop().replace(/\.json$/, '');
    const walk = (node, path) => {
      for (const [k, v] of Object.entries(node)) {
        if (typeof v === 'string') messages[locale][`${path}.${k}`] = v;
        else if (v && typeof v === 'object') walk(v, `${path}.${k}`);
      }
    };
    walk(JSON.parse(git('show', `${ref}:${file}`)), name);
  }
}

const problems = [];
const uniq = (list) => [...new Set(list)];
const out = terms.map((t) => {
  const row = { id: t.id, group: t.group, keys: t.keys };
  for (const locale of locales) {
    row[locale] = uniq(
      t.keys.map((key) => {
        const value = messages[locale][key];
        if (value === undefined) problems.push(`${t.id}: no "${key}" in the ${locale} messages`);
        return value;
      }).filter(Boolean),
    );
  }
  if (t.pair) row.pair = true;
  if (t.match) row.match = t.match;
  if (t.enMatch) row.enMatch = t.enMatch;
  return row;
});

if (problems.length) {
  console.error('\n  The app no longer has these keys. Fix scripts/20261113-1401-app-terms.config.mjs:\n');
  for (const p of problems) console.error(`    ${p}`);
  console.error('');
  process.exit(1);
}

// Where the app itself uses two words for one English label. Statuses are left
// out: there the word follows the sentence ("Replied" as a state, as a count).
const drift = [];
const lower = (s) => s.toLocaleLowerCase();
for (const row of out) {
  if (row.group === 'Statuses') continue;
  for (const en of row.en) {
    const keys = Object.keys(messages.en).filter((k) => lower(messages.en[k]) === lower(en));
    if (keys.length < 2) continue;
    for (const locale of locales.filter((l) => l !== 'en')) {
      const variants = {};
      for (const key of keys) {
        const value = messages[locale][key];
        if (value === undefined) continue;
        (variants[lower(value)] ??= { text: value, keys: [] }).keys.push(key);
      }
      const list = Object.values(variants);
      if (list.length > 1) drift.push({ term: row.id, en, locale, variants: list });
    }
  }
}

const data = {
  source: { repo: 'hubsell-client', ref, commit, date: commitDate, path: MESSAGES },
  locales,
  terms: out,
};
writeFileSync(resolve(root, 'docs/20261113-1401-app-terms.json'), JSON.stringify(data, null, 2) + '\n');

const cell = (list) => list.map((v) => v.replace(/\|/g, '\\|')).join(' / ');
const md = [];
md.push('# App terms in six languages');
md.push('');
md.push('Generated by `npm run terms` (`scripts/20261113-1401-app-terms.mjs`). Do not edit by hand: change');
md.push('`scripts/20261113-1401-app-terms.config.mjs` (which terms) or the app\'s message files (the words).');
md.push('');
md.push(`Source: hubsell-client \`${ref}\` at \`${commit}\` (${commitDate}), \`${MESSAGES}/<locale>/\`.`);
md.push('');
md.push('The website uses the same words as the app in every language (owner decision');
md.push('2026-11-12). When a page needs one of the terms below, use the word in this table.');
md.push('Where two forms are given they are singular / plural. `npm run build` checks the');
md.push('built pages against this list (`scripts/20261113-1401-check-app-terms.mjs`); see `CLAUDE.md`,');
md.push('"Internationalisation".');
for (const group of uniq(out.map((r) => r.group))) {
  md.push('');
  md.push(`## ${group}`);
  md.push('');
  md.push('| English | German | Dutch | French | Spanish | Portuguese (Brazil) |');
  md.push('|---|---|---|---|---|---|');
  for (const r of out.filter((x) => x.group === group)) {
    md.push(`| ${cell(r.en)} | ${cell(r.de)} | ${cell(r.nl)} | ${cell(r.fr)} | ${cell(r.es)} | ${cell(r.pt)} |`);
  }
}
md.push('');
md.push('## Where the app uses two words for the same thing');
md.push('');
if (!drift.length) {
  md.push('None found.');
} else {
  md.push('The same English label is translated in more than one way inside the app. The');
  md.push('website uses the word from the tables above (the navigation); the others are for');
  md.push('the app team to line up.');
  md.push('');
  md.push('| English | Language | Words in the app (message key) |');
  md.push('|---|---|---|');
  for (const d of drift) {
    const words = d.variants.map((v) => `${v.text} (\`${v.keys[0]}\`${v.keys.length > 1 ? `, +${v.keys.length - 1}` : ''})`).join('; ');
    md.push(`| ${d.en} | ${d.locale} | ${words.replace(/\|/g, '\\|')} |`);
  }
}
md.push('');
writeFileSync(resolve(root, 'docs/20261113-1401-APP-TERMS.md'), md.join('\n'));

console.log(`\n  ${out.length} terms from hubsell-client ${ref} (${commit}) -> docs/20261113-1401-app-terms.json, docs/20261113-1401-APP-TERMS.md`);
console.log(`  ${drift.length} place(s) where the app uses two words for one label (listed in APP-TERMS.md)\n`);
